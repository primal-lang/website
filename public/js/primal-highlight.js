// The icon carries the outcome visually and the label carries it to assistive
// technology, so neither state depends on colour alone.
function setCopyButtonState(button, styleClass, icon, label) {
  button.classList.remove('copied', 'copy-failed');

  if (styleClass) {
    button.classList.add(styleClass);
  }

  button.innerHTML = icon;
  button.setAttribute('aria-label', label);
}

function flashCopyButtonState(button, styleClass, icon, label) {
  setCopyButtonState(button, styleClass, icon, label);

  setTimeout(function () {
    setCopyButtonState(button, null, COPY_ICON, 'Copy code');
  }, 2000);
}

function addCopyButton(sample, source) {
  const button = document.createElement('button');
  button.className = 'code-copy-btn';
  button.type = 'button';
  button.setAttribute('aria-label', 'Copy code');
  button.innerHTML = COPY_ICON;

  button.addEventListener('click', function () {
    // The Clipboard API is missing outside secure contexts and can reject even
    // where it exists, so the tick only appears once the copy has succeeded.
    if (!navigator.clipboard) {
      flashCopyButtonState(button, 'copy-failed', COPY_FAILED_ICON, 'Copy failed');

      return;
    }

    navigator.clipboard
      .writeText(source())
      .then(function () {
        flashCopyButtonState(button, 'copied', COPIED_ICON, 'Code copied');
      })
      .catch(function () {
        flashCopyButtonState(button, 'copy-failed', COPY_FAILED_ICON, 'Copy failed');
      });
  });

  sample.appendChild(button);
}

function highlightCodeSamples(root) {
  const samples = (root || document).querySelectorAll('.code-sample');

  samples.forEach(function (sample) {
    if (sample.dataset.highlighted === 'true') {
      return;
    }

    sample.dataset.highlighted = 'true';

    const code = sample.querySelector('code');

    if (code) {
      const source = code.textContent;

      if (sample.dataset.lang !== 'text') {
        code.innerHTML = primalRender(source, sample.dataset.lang || 'primal');
      }

      addCopyButton(sample, function () {
        return source;
      });

      return;
    }

    // Samples written as plain text in the markup, with no <pre><code> wrapper.
    addCopyButton(sample, function () {
      return sample.textContent;
    });
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', function () {
    highlightCodeSamples();
  });
} else {
  highlightCodeSamples();
}
