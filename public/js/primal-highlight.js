/*
 * Primal syntax highlighting.
 *
 * The lexer mirrors primal-sdk/lib/compiler/lexical/lexical_analyzer.dart with one
 * deliberate difference: it never throws. A highlighter runs on half-typed source,
 * so anything it cannot classify is emitted as unstyled text instead of aborting
 * the whole render.
 *
 * Two dialects share the lexer and differ only in how identifiers are resolved:
 *   primal    — real source; resolves definitions, parameters and let bindings
 *   signature — documentation pseudo-syntax such as `str_at(a: String): String`
 *   text      — not Primal at all (shell commands); rendered verbatim
 */

const PRIMAL_KEYWORDS = new Set(['if', 'else', 'let', 'in', 'and', 'or', 'not']);
const PRIMAL_BOOLEANS = new Set(['true', 'false']);

// Longest first, so '->' is never read as '-' followed by '>'.
const PRIMAL_OPERATORS = [
  '->', '==', '!=', '>=', '<=', '&&', '||',
  '+', '-', '*', '/', '%', '@', '|', '&', '!', '<', '>', '=',
];

// '...' only ever appears in documentation signatures, but recognising it here
// keeps it out of the unclassified bucket in both dialects.
const PRIMAL_PUNCTUATION = ['...', '(', ')', '[', ']', '{', '}', ',', ':'];

const PRIMAL_TOKEN_CLASSES = {
  comment: 'tok-comment',
  string: 'tok-string',
  number: 'tok-number',
  boolean: 'tok-boolean',
  keyword: 'tok-keyword',
  operator: 'tok-operator',
  punctuation: 'tok-punctuation',
  native: 'tok-native',
  definition: 'tok-definition',
  param: 'tok-param',
  binding: 'tok-binding',
  identifier: 'tok-identifier',
  type: 'tok-type',
};

// Generated by scripts/gen-natives.sh. Missing it degrades colour, never behaviour.
const PRIMAL_NATIVE_NAMES =
  typeof PRIMAL_NATIVES !== 'undefined' ? PRIMAL_NATIVES : new Set();

function primalIsLetter(character) {
  return (character >= 'a' && character <= 'z') || (character >= 'A' && character <= 'Z');
}

function primalIsDigit(character) {
  return character >= '0' && character <= '9';
}

function primalIsIdentifierPart(character) {
  return primalIsLetter(character) || primalIsDigit(character) || character === '_';
}

/*
 * Splits source into tokens that cover every character, whitespace included, so
 * joining their values reproduces the input exactly. `atColumnZero` records that
 * the token opens its line with no indentation, which is how top-level
 * definitions are told apart from the indented bindings inside one.
 */
function primalTokenize(source) {
  const tokens = [];
  let index = 0;
  let atColumnZero = true;

  function push(type, value) {
    tokens.push({ type: type, value: value, atColumnZero: atColumnZero });
    atColumnZero = false;
  }

  while (index < source.length) {
    const character = source[index];

    if (/\s/.test(character)) {
      let end = index;

      while (end < source.length && /\s/.test(source[end])) {
        end++;
      }

      const value = source.slice(index, end);
      tokens.push({ type: 'space', value: value, atColumnZero: atColumnZero });
      // A run ending in a newline puts the next token at column 0; one ending in
      // spaces means the next token is indented, and so is not a definition.
      atColumnZero = value.endsWith('\n');
      index = end;
      continue;
    }

    if (character === '/' && source[index + 1] === '/') {
      let end = source.indexOf('\n', index);

      if (end === -1) {
        end = source.length;
      }

      push('comment', source.slice(index, end));
      index = end;
      continue;
    }

    // Block comments do not nest in the SDK, so the first '*/' closes them.
    if (character === '/' && source[index + 1] === '*') {
      const close = source.indexOf('*/', index + 2);
      const end = close === -1 ? source.length : close + 2;
      push('comment', source.slice(index, end));
      index = end;
      continue;
    }

    // Both quote styles are valid and strings may span lines. An unterminated
    // quote runs to the end of the input, which is what an editor should show
    // while the closing quote is still being typed.
    if (character === '"' || character === "'") {
      let end = index + 1;

      while (end < source.length) {
        if (source[end] === '\\') {
          end += 2;
          continue;
        }

        if (source[end] === character) {
          end++;
          break;
        }

        end++;
      }

      push('string', source.slice(index, Math.min(end, source.length)));
      index = Math.min(end, source.length);
      continue;
    }

    if (primalIsDigit(character)) {
      let end = index;

      while (end < source.length && (primalIsDigit(source[end]) || source[end] === '_')) {
        end++;
      }

      if (source[end] === '.' && primalIsDigit(source[end + 1])) {
        end++;

        while (end < source.length && (primalIsDigit(source[end]) || source[end] === '_')) {
          end++;
        }
      }

      if (source[end] === 'e' || source[end] === 'E') {
        let probe = end + 1;

        if (source[probe] === '+' || source[probe] === '-') {
          probe++;
        }

        // Only consume the exponent if it is complete, so `1e` keeps the `e` as
        // a separate identifier rather than swallowing it into the number.
        if (primalIsDigit(source[probe])) {
          end = probe;

          while (end < source.length && (primalIsDigit(source[end]) || source[end] === '_')) {
            end++;
          }
        }
      }

      push('number', source.slice(index, end));
      index = end;
      continue;
    }

    if (primalIsLetter(character)) {
      let end = index;

      while (end < source.length && primalIsIdentifierPart(source[end])) {
        end++;
      }

      const value = source.slice(index, end);

      if (PRIMAL_BOOLEANS.has(value)) {
        push('boolean', value);
      } else if (PRIMAL_KEYWORDS.has(value)) {
        push('keyword', value);
      } else {
        push('identifier', value);
      }

      index = end;
      continue;
    }

    const operator = PRIMAL_OPERATORS.find(function (candidate) {
      return source.startsWith(candidate, index);
    });

    if (operator) {
      push('operator', operator);
      index += operator.length;
      continue;
    }

    const punctuation = PRIMAL_PUNCTUATION.find(function (candidate) {
      return source.startsWith(candidate, index);
    });

    if (punctuation) {
      push('punctuation', punctuation);
      index += punctuation.length;
      continue;
    }

    push('text', character);
    index++;
  }

  return tokens;
}

function primalNextCodeIndex(tokens, from) {
  for (let index = from + 1; index < tokens.length; index++) {
    if (tokens[index].type !== 'space' && tokens[index].type !== 'comment') {
      return index;
    }
  }

  return -1;
}

function primalPreviousCodeIndex(tokens, from) {
  for (let index = from - 1; index >= 0; index--) {
    if (tokens[index].type !== 'space' && tokens[index].type !== 'comment') {
      return index;
    }
  }

  return -1;
}

/*
 * Recognises `name = expr` and `name(a, b) = expr` at the start of a line, and
 * returns the declared parameters. Requiring the full shape down to the '=' is
 * what keeps a bare call such as `quicksort([3, 1, 2])` from being mistaken for
 * a definition when a sample opens with one.
 */
function primalDefinitionAt(tokens, start) {
  let cursor = primalNextCodeIndex(tokens, start);

  if (cursor === -1) {
    return null;
  }

  if (tokens[cursor].type === 'operator' && tokens[cursor].value === '=') {
    return { parameters: [] };
  }

  if (tokens[cursor].value !== '(') {
    return null;
  }

  const parameters = [];
  cursor = primalNextCodeIndex(tokens, cursor);

  if (cursor === -1) {
    return null;
  }

  if (tokens[cursor].value !== ')') {
    while (true) {
      if (tokens[cursor].type !== 'identifier') {
        return null;
      }

      parameters.push(tokens[cursor].value);
      cursor = primalNextCodeIndex(tokens, cursor);

      if (cursor === -1) {
        return null;
      }

      if (tokens[cursor].value === ',') {
        cursor = primalNextCodeIndex(tokens, cursor);

        if (cursor === -1) {
          return null;
        }

        continue;
      }

      if (tokens[cursor].value === ')') {
        break;
      }

      return null;
    }
  }

  cursor = primalNextCodeIndex(tokens, cursor);

  if (cursor === -1 || tokens[cursor].type !== 'operator' || tokens[cursor].value !== '=') {
    return null;
  }

  return { parameters: parameters };
}

/*
 * Lambda parameters, which the parser only accepts parenthesised: `() ->`,
 * `(a) ->`, `(a, b) ->`. Found by walking back from each arrow to its '('.
 */
function primalCollectLambdaParameters(tokens, from, to, into) {
  for (let index = from; index < to; index++) {
    if (tokens[index].type !== 'operator' || tokens[index].value !== '->') {
      continue;
    }

    let cursor = primalPreviousCodeIndex(tokens, index);

    if (cursor === -1 || tokens[cursor].value !== ')') {
      continue;
    }

    let depth = 0;

    while (cursor >= from) {
      const value = tokens[cursor].value;
      const isPunctuation = tokens[cursor].type === 'punctuation';

      if (isPunctuation && value === ')') {
        depth++;
      } else if (isPunctuation && value === '(') {
        depth--;

        if (depth === 0) {
          break;
        }
      } else if (depth === 1 && tokens[cursor].type === 'identifier') {
        into.add(tokens[cursor].value);
      }

      cursor--;
    }
  }
}

/*
 * Names bound by `let a = 1, b = 2 in ...`. Nested lets are tracked by depth so
 * an inner `in` does not close the outer binding list.
 */
function primalCollectLetBindings(tokens, from, to, into) {
  let depth = 0;

  for (let index = from; index < to; index++) {
    const token = tokens[index];

    if (token.type === 'keyword' && token.value === 'let') {
      depth++;
      continue;
    }

    if (token.type === 'keyword' && token.value === 'in') {
      depth = Math.max(0, depth - 1);
      continue;
    }

    if (depth === 0 || token.type !== 'identifier') {
      continue;
    }

    const next = primalNextCodeIndex(tokens, index);

    if (next !== -1 && tokens[next].type === 'operator' && tokens[next].value === '=') {
      into.add(token.value);
    }
  }
}

/*
 * Resolves identifiers in real Primal source.
 *
 * Scope is approximated per top-level definition rather than tracked properly:
 * every parameter, lambda parameter and let binding inside one definition goes
 * into a single set. Binding starts are unambiguous in Primal; only their ends
 * are, which is exactly what this avoids needing. The one case it cannot tell
 * apart is a name used as both a parameter and a let binding in the same
 * definition — both are locals, and it reports a binding.
 */
function primalClassify(tokens) {
  const definitionStarts = [];
  const definitions = [];

  for (let index = 0; index < tokens.length; index++) {
    const token = tokens[index];

    if (token.type !== 'identifier' || !token.atColumnZero) {
      continue;
    }

    const definition = primalDefinitionAt(tokens, index);

    if (definition) {
      definitionStarts.push(index);
      definitions.push(definition);
    }
  }

  const declaredNames = new Set(
    definitionStarts.map(function (start) {
      return tokens[start].value;
    })
  );

  const parametersByRange = [];
  const bindingsByRange = [];

  for (let range = 0; range < definitionStarts.length; range++) {
    const from = definitionStarts[range];
    const to = range + 1 < definitionStarts.length ? definitionStarts[range + 1] : tokens.length;
    const parameters = new Set(definitions[range].parameters);
    const bindings = new Set();

    primalCollectLambdaParameters(tokens, from, to, parameters);
    primalCollectLetBindings(tokens, from, to, bindings);

    parametersByRange.push(parameters);
    bindingsByRange.push(bindings);
  }

  let range = -1;

  for (let index = 0; index < tokens.length; index++) {
    if (range + 1 < definitionStarts.length && index === definitionStarts[range + 1]) {
      range++;
    }

    const token = tokens[index];

    if (token.type !== 'identifier') {
      continue;
    }

    const parameters = range >= 0 ? parametersByRange[range] : null;
    const bindings = range >= 0 ? bindingsByRange[range] : null;

    if (declaredNames.has(token.value)) {
      token.type = 'definition';
    } else if (bindings && bindings.has(token.value)) {
      token.type = 'binding';
    } else if (parameters && parameters.has(token.value)) {
      token.type = 'param';
    } else if (PRIMAL_NATIVE_NAMES.has(token.value)) {
      token.type = 'native';
    }
  }

  return tokens;
}

/*
 * Resolves identifiers in documentation signatures. These are Primal-shaped but
 * not Primal: `str_at(a: String, b: Number): String`, and also looser forms such
 * as `let name1 = expr1, ... in body` and `[Any, Any, ...]: List`. So the rule is
 * positional rather than a fixed grammar — an identifier after ':' names a type,
 * one introducing a call names the function, and everything else is a
 * placeholder.
 *
 * Capitalisation settles the bracket forms, where a type has no ':' in front of
 * it. Every type name in the docs is capitalised and every placeholder is
 * lowercase, so the two never collide. This only holds because the block is
 * known to be a signature; real Primal source is classified by primalClassify,
 * which makes no such assumption.
 */
function primalClassifySignature(tokens) {
  for (let index = 0; index < tokens.length; index++) {
    const token = tokens[index];

    if (token.type !== 'identifier') {
      continue;
    }

    const previous = primalPreviousCodeIndex(tokens, index);

    if (previous !== -1 && tokens[previous].value === ':') {
      token.type = 'type';
      continue;
    }

    if (/^[A-Z]/.test(token.value)) {
      token.type = 'type';
      continue;
    }

    if (PRIMAL_NATIVE_NAMES.has(token.value)) {
      token.type = 'native';
      continue;
    }

    const next = primalNextCodeIndex(tokens, index);
    token.type = next !== -1 && tokens[next].value === '(' ? 'definition' : 'param';
  }

  return tokens;
}

function primalEscapeHtml(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function primalRender(source, dialect) {
  if (dialect === 'text') {
    return primalEscapeHtml(source);
  }

  const tokens = primalTokenize(source);

  if (dialect === 'signature') {
    primalClassifySignature(tokens);
  } else {
    primalClassify(tokens);
  }

  return tokens
    .map(function (token) {
      const escaped = primalEscapeHtml(token.value);
      const className = PRIMAL_TOKEN_CLASSES[token.type];

      return className ? '<span class="' + className + '">' + escaped + '</span>' : escaped;
    })
    .join('');
}

